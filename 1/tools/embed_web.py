#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate web_content_gz.h from web_content.h.

The web UI lives inside C++ string literals in web_content.h.  This script
parses those literals (ignoring C++ comments), gzip-compresses the resulting
HTML, and writes the PROGMEM byte arrays used by 1.ino.

Usage:
    python tools/embed_web.py
    python tools/embed_web.py --output .tmp/web_content_gz.h

Only Python's standard library is required.
"""

import argparse
import gzip
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SRC = os.path.join(ROOT, "web_content.h")
DEFAULT_OUT = os.path.join(ROOT, "web_content_gz.h")


def _skip_space_and_comments(text, i):
    """Advance past whitespace, // comments and /* ... */ comments."""
    n = len(text)
    while i < n:
        c = text[i]
        if c.isspace():
            i += 1
        elif text.startswith("//", i):
            end = text.find("\n", i)
            i = n if end < 0 else end + 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                raise ValueError("unterminated /* comment")
            i = end + 2
        else:
            break
    return i


def _read_c_string(text, i):
    """Read one C string literal starting at text[i] == '\"'. Return (value, next)."""
    if text[i] != '"':
        raise ValueError("expected string literal at offset %d" % i)
    i += 1
    out = []
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"':
            return "".join(out), i + 1
        if c != "\\":
            out.append(c)
            i += 1
            continue

        i += 1
        if i >= n:
            raise ValueError("unterminated escape")
        e = text[i]
        if e == "n":
            out.append("\n"); i += 1
        elif e == "r":
            out.append("\r"); i += 1
        elif e == "t":
            out.append("\t"); i += 1
        elif e == "\\":
            out.append("\\"); i += 1
        elif e == '"':
            out.append('"'); i += 1
        elif e == "'":
            out.append("'"); i += 1
        elif e == "0":
            out.append("\0"); i += 1
        elif e == "x":
            hex_digits = text[i + 1:i + 3]
            if len(hex_digits) != 2:
                raise ValueError("bad \\x escape")
            out.append(chr(int(hex_digits, 16)))
            i += 3
        else:
            # Unknown escape: C++ keeps the character after the backslash.
            out.append(e)
            i += 1
    raise ValueError("unterminated string literal")


def extract_array(text, name):
    """Extract concatenated C string literals from a PROGMEM char array."""
    marker = "const char %s[] PROGMEM" % name
    start = text.find(marker)
    if start < 0:
        raise ValueError("array not found: %s" % name)
    i = text.find("=", start)
    if i < 0:
        raise ValueError("'=' not found for %s" % name)
    i += 1

    pieces = []
    n = len(text)
    while True:
        i = _skip_space_and_comments(text, i)
        if i >= n:
            raise ValueError("unexpected EOF while reading %s" % name)
        if text[i] == '"':
            value, i = _read_c_string(text, i)
            pieces.append(value)
        elif text[i] == ";":
            return "".join(pieces)
        else:
            # Ignore separators such as commas; normal arrays do not need them.
            i += 1


def gzip_array(data):
    """Return (compressed_size, C initializer lines)."""
    gz = gzip.compress(data.encode("utf-8"), compresslevel=9, mtime=0)
    lines = []
    for offset in range(0, len(gz), 16):
        chunk = gz[offset:offset + 16]
        suffix = "," if offset + 16 < len(gz) else ""
        lines.append("  " + ", ".join("0x%02X" % b for b in chunk) + suffix)
    return len(gz), "\n".join(lines)


def render_header(main_html, ota_html):
    main_len, main_lines = gzip_array(main_html)
    ota_len, ota_lines = gzip_array(ota_html)
    return (
        "#pragma once\n"
        "// OneUI 8.5 pages - pre-compressed gzip (generated by tools/embed_web.py)\n"
        "// DO NOT hand-edit this file.\n"
        "#include <Arduino.h>\n\n"
        "static const uint8_t PAGE_HTML_MAIN_GZ[] PROGMEM = {\n"
        + main_lines + "\n};\n"
        "static const size_t PAGE_HTML_MAIN_GZ_LEN = sizeof(PAGE_HTML_MAIN_GZ);\n\n"
        "static const uint8_t PAGE_HTML_OTA_GZ[] PROGMEM = {\n"
        + ota_lines + "\n};\n"
        "static const size_t PAGE_HTML_OTA_GZ_LEN = sizeof(PAGE_HTML_OTA_GZ);\n",
        main_len,
        ota_len,
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", default=DEFAULT_SRC, help="input web_content.h")
    parser.add_argument("--output", default=DEFAULT_OUT, help="output web_content_gz.h")
    args = parser.parse_args()

    with open(args.src, "r", encoding="utf-8") as f:
        text = f.read()

    main_html = extract_array(text, "PAGE_HTML_MAIN")
    ota_html = extract_array(text, "PAGE_HTML_OTA")
    header, main_len, ota_len = render_header(main_html, ota_html)

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)

    print("PAGE_HTML_MAIN: %d chars -> gzip %d bytes" % (len(main_html), main_len))
    print("PAGE_HTML_OTA : %d chars -> gzip %d bytes" % (len(ota_html), ota_len))
    print("wrote", args.output)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("error:", exc, file=sys.stderr)
        sys.exit(1)
